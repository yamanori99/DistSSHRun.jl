#!/usr/bin/env bash
# Write .generated/env.sh with absolute -F paths for DistSSHRun / git SSH.
# Called by docker-ssh and apple-container-ssh up.sh after ssh_config is final.
# Path + flags only — never private key material (gitleaks / gitignore).
#
# Quoting layers:
# 1. env.sh assignment must survive `source` without expanding metacharacters.
# 2. After source, DISTRIBUTED_SSH_OPTS is split by Julia `Base.shell_split`, and
#    GIT_SSH_COMMAND is parsed by git's shell. The -F path must stay one data
#    argument (spaces, quotes, $, `, ;, etc. are path bytes, not syntax).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
GEN="${ROOT}/.generated"
SSH_CONFIG="${GEN}/ssh_config"
ENV_FILE="${GEN}/env.sh"

if [[ ! -f "${SSH_CONFIG}" ]]; then
  echo "missing ${SSH_CONFIG}; run up.sh first" >&2
  exit 1
fi

# POSIX single-quote one word (same idea as DistSSHBase.posix_quote).
_posix_sq() {
  printf "'%s'" "${1//\'/\'\\\'\'}"
}

path_q="$(_posix_sq "${SSH_CONFIG}")"
opts_content="-F ${path_q} -o RequestTTY=no"
git_content="ssh -F ${path_q} -o RequestTTY=no"

umask 077
{
  echo "# Generated by docker-ssh / apple-container up.sh. Not for commit."
  # %q so sourcing does not re-expand $, backticks, or spaces in the value.
  printf 'DISTRIBUTED_SSH_OPTS=%q\n' "${opts_content}"
  printf 'GIT_SSH_COMMAND=%q\n' "${git_content}"
} >"${ENV_FILE}"

echo "Wrote ${ENV_FILE}"
